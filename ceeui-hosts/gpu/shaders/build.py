"""Compiles the Vulkan shaders to SPIR-V and writes them as C arrays to src/vulkan_shaders.h, which is checked in,
so building the host needs no shader compiler. Run it after changing a shader, where glslangValidator is installed
(Debian: glslang-tools; the Vulkan SDK elsewhere):

    python3 shaders/build.py
"""

import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
STAGES = [  # (file, stage, C name)
    ("shapes.vert", "vert", "cw_spv_shapes_vert"),
    ("shapes.frag", "frag", "cw_spv_shapes_frag"),
    ("fill.frag", "frag", "cw_spv_fill_frag"),
    ("composite.frag", "frag", "cw_spv_composite_frag"),
    ("full.vert", "vert", "cw_spv_full_vert"),
    ("box.frag", "frag", "cw_spv_box_frag"),
]


def main():
    common = open(os.path.join(HERE, "common.glsl"), encoding="utf-8").read()
    out = ["/* SPDX-License-Identifier: MIT */",
           "/* Generated by shaders/build.py from the GLSL in shaders/: do not edit. */",
           "#include <stdint.h>", ""]
    with tempfile.TemporaryDirectory() as work:
        for name, stage, symbol in STAGES:
            source = "#version 450\n" + common + "\n" + open(os.path.join(HERE, name), encoding="utf-8").read()
            src = os.path.join(work, name + ".glsl")
            spv = os.path.join(work, name + ".spv")
            with open(src, "w", encoding="utf-8") as f:
                f.write(source)
            r = subprocess.run(["glslangValidator", "-V", "-S", stage, "-o", spv, src], capture_output=True, text=True)
            if r.returncode != 0:
                sys.exit(f"build.py: {name}:\n{r.stdout}{r.stderr}")
            data = open(spv, "rb").read()
            words = [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]
            out.append(f"static const uint32_t {symbol}[{len(words)}] = {{")
            for i in range(0, len(words), 8):
                out.append("    " + ", ".join(f"0x{w:08x}u" for w in words[i:i + 8]) + ",")
            out.append("};")
            out.append("")
    with open(os.path.join(HERE, "..", "src", "vulkan_shaders.h"), "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print(f"build.py: {len(STAGES)} shaders")


if __name__ == "__main__":
    main()
