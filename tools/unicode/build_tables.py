"""Builds claywind/src/unicode_data.cee from the Unicode Character Database: the properties line breaking (UAX #14)
and grapheme clusters (UAX #29) need, for every code point, as one sorted table of ranges. The generated file is
checked in, so building ClayWind needs neither this script nor the UCD. Run it after a Unicode update:

    python3 tools/unicode/build_tables.py UCD_DIR

UCD_DIR holds, from https://www.unicode.org/Public/<version>/ucd/: LineBreak.txt, EastAsianWidth.txt,
DerivedCoreProperties.txt, extracted/DerivedGeneralCategory.txt (as DerivedGeneralCategory.txt),
auxiliary/GraphemeBreakProperty.txt and emoji/emoji-data.txt.

Each range's value packs:
  bits 0-5    Line_Break class (LB_* below)
  bits 6-9    Grapheme_Cluster_Break (GCB_*)
  bit 10      Extended_Pictographic
  bit 11      East_Asian_Width F, W or H (UAX #14's $EastAsian)
  bits 12-13  Indic_Conjunct_Break: 0 None, 1 Consonant, 2 Extend, 3 Linker
  bits 14-16  General_Category, as far as the rules ask: 0 other, 1 Mn, 2 Mc, 3 Me, 4 Pi, 5 Pf, 6 Cn
"""

import os
import re
import sys

LB = ["XX", "BK", "CR", "LF", "NL", "SP", "ZW", "WJ", "GL", "BA", "BB", "B2", "HY", "CB", "CL", "CP", "EX", "IN",
      "NS", "OP", "QU", "IS", "NU", "PO", "PR", "SY", "AI", "AK", "AL", "AP", "AS", "CJ", "EB", "EM", "H2", "H3", "HL",
      "ID", "JL", "JV", "JT", "RI", "SA", "SG", "VF", "VI", "ZWJ", "CM"]
GCB = ["Other", "CR", "LF", "Control", "Extend", "ZWJ", "Regional_Indicator", "Prepend", "SpacingMark", "L", "V", "T",
       "LV", "LVT"]
INCB = {"None": 0, "Consonant": 1, "Extend": 2, "Linker": 3}
GC = {"Mn": 1, "Mc": 2, "Me": 3, "Pi": 4, "Pf": 5, "Cn": 6}
LIMIT = 0x110000


def entries(path):
    """(first, last, fields) for every data line, and the @missing defaults first."""
    missing = []
    data = []
    for line in open(path, encoding="utf-8"):
        m = re.match(r"#\s*@missing:\s*([0-9A-F]+)\.\.([0-9A-F]+)\s*;\s*(.*)", line)
        if m:
            missing.append((int(m.group(1), 16), int(m.group(2), 16), [f.strip() for f in m.group(3).split(";")]))
            continue
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        fields = [f.strip() for f in line.split(";")]
        span = fields[0].split("..")
        first = int(span[0], 16)
        last = int(span[1], 16) if len(span) > 1 else first
        data.append((first, last, fields[1:]))
    return missing, data


def fill(table, path, value_of):
    missing, data = entries(path)
    for first, last, fields in missing + data:
        v = value_of(fields)
        if v is not None:
            for cp in range(first, last + 1):
                table[cp] = v


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    ucd = sys.argv[1]
    lb = [0] * LIMIT
    fill(lb, os.path.join(ucd, "LineBreak.txt"), lambda f: LB.index(f[0]))
    gcb = [0] * LIMIT
    fill(gcb, os.path.join(ucd, "GraphemeBreakProperty.txt"), lambda f: GCB.index(f[0]))
    pict = [0] * LIMIT
    fill(pict, os.path.join(ucd, "emoji-data.txt"), lambda f: 1 if f[0] == "Extended_Pictographic" else None)
    wide = [0] * LIMIT
    fill(wide, os.path.join(ucd, "EastAsianWidth.txt"), lambda f: 1 if f[0] in ("F", "W", "H") else 0)
    incb = [0] * LIMIT
    fill(incb, os.path.join(ucd, "DerivedCoreProperties.txt"),
         lambda f: INCB[f[1]] if f[0] == "InCB" and len(f) > 1 else None)
    gc = [GC["Cn"]] * LIMIT
    fill(gc, os.path.join(ucd, "DerivedGeneralCategory.txt"), lambda f: GC.get(f[0], 0))
    version = "?"
    m = re.search(r"LineBreak-([0-9.]+)\.txt", open(os.path.join(ucd, "LineBreak.txt"), encoding="utf-8").readline())
    if m:
        version = m.group(1)

    ranges = []
    previous = None
    for cp in range(LIMIT):
        v = lb[cp] | gcb[cp] << 6 | pict[cp] << 10 | wide[cp] << 11 | incb[cp] << 12 | gc[cp] << 14
        if v != previous:
            ranges.append((cp, v))
            previous = v

    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(here, "..", "..", "claywind", "src", "unicode_data.cee")
    lines = [
        "// SPDX-License-Identifier: MIT",
        f"// Generated by tools/unicode/build_tables.py from the Unicode {version} character database: do not edit.",
        "// Unicode data is under the Unicode License v3 (https://www.unicode.org/license.txt).",
        "",
        f"/// The Unicode version these properties are from.",
        f'public const UNICODE_VERSION: StringView = "{version}";',
        "",
    ]
    for i, name in enumerate(LB):
        lines.append(f"const LB_{name}: u32 = {i};")
    lines.append("")
    for i, name in enumerate(GCB):
        lines.append(f"const GCB_{name.upper()}: u32 = {i};")
    lines.append("")
    lines += [
        "const GC_MN: u32 = 1;",
        "const GC_MC: u32 = 2;",
        "const GC_ME: u32 = 3;",
        "const GC_PI: u32 = 4;",
        "const GC_PF: u32 = 5;",
        "const GC_CN: u32 = 6;",
        "",
        "/// ASCII's properties, for a lookup without the search.",
        "const UNICODE_ASCII: [u32; 128] = [",
    ]
    ascii = [lb[cp] | gcb[cp] << 6 | pict[cp] << 10 | wide[cp] << 11 | incb[cp] << 12 | gc[cp] << 14 for cp in range(128)]
    for k in range(0, 128, 8):
        lines.append("    " + ", ".join(f"0x{v:X}" for v in ascii[k:k + 8]) + ",")
    lines += [
        "];",
        "",
        f"/// How many ranges UNICODE_RANGES holds.",
        f"const UNICODE_RANGE_COUNT: usize = {len(ranges)};",
        "",
        "/// Every code point's properties as (first code point, packed value) pairs, sorted; a range runs to the next",
        "/// pair's first code point. See tools/unicode/build_tables.py for the packing.",
        f"const UNICODE_RANGES: [u32; {len(ranges) * 2}] = [",
    ]
    row = []
    for first, v in ranges:
        row.append(f"0x{first:X}, 0x{v:X}")
        if len(row) == 6:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ", ".join(row) + ",")
    lines.append("];")
    lines.append("")
    open(out, "w", encoding="utf-8").write("\n".join(lines))
    print(f"build_tables.py: Unicode {version}, {len(ranges)} ranges -> {os.path.relpath(out)}")


if __name__ == "__main__":
    main()
