"""Builds ceeui/src/indic_data.cee: each code point's Indic shaping category and position, as HarfBuzz's Indic
shaper assigns them, and the canonical decompositions the shaper applies. The generated file is checked in.

    python3 tools/unicode/build_indic.py HARFBUZZ_SRC UCD_DIR

HARFBUZZ_SRC holds HarfBuzz's src/hb-ot-shaper-indic-table.cc (generated by HarfBuzz from the UCD's
IndicSyllabicCategory.txt and IndicPositionalCategory.txt with its own overrides; MIT licence, see
THIRD_PARTY_NOTICES). UCD_DIR holds UnicodeData.txt and CompositionExclusions.txt.

Categories (the syllable machine's alphabet) and positions are HarfBuzz's numbers (hb-ot-shaper-indic-machine.rl,
hb-ot-shaper-indic.hh); a code point HarfBuzz gives no Indic category is X at END.
"""

import os
import re
import sys

CATEGORY = {"X": 0, "C": 1, "V": 2, "N": 3, "H": 4, "ZWNJ": 5, "ZWJ": 6, "M": 7, "SM": 8, "A": 9, "GB": 10,
            "DC": 11, "RS": 12, "MP": 13, "Rf": 14, "R": 15, "CM": 16, "S": 17, "CS": 18, "SP": 57}
POSITION = {"L": 3, "C": 4, "A": 5, "T": 6, "BS": 7, "B": 8, "AS": 9, "R": 11, "AP": 12, "SM": 13, "X": 14,
            "LM": 2}


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    src = open(os.path.join(sys.argv[1], "hb-ot-shaper-indic-table.cc"), encoding="utf-8").read()
    u8 = re.search(r"static const uint8_t _hb_indic_u8\[\d+\]=\s*\{(.*?)\};", src, re.S).group(1)
    u8 = [int(x) for x in re.findall(r"\d+", re.sub(r"/\*.*?\*/", "", u8))]
    values = re.findall(r"_\((\w+),(\w+)\)", re.search(r"_hb_indic_values\[\d+\]=\s*\{(.*?)\};", src, re.S).group(1))
    limit = int(re.search(r"return u<(\d+)u", src).group(1))
    default = int(re.search(r": (\d+);\s*\}\s*uint16_t\s*hb_indic_get_categories", src).group(1))

    def index(u):
        # HarfBuzz's packtab lookup ([2^8,2^3,2^3,2^2,2^1]).
        if u >= limit:
            return default
        a = u8[u >> 9]
        b = u8[143 + a + ((u >> 6) & 7)]
        c = u8[279 + (b << 3) + ((u >> 3) & 7)]
        d = u8[598 + (c << 2) + ((u >> 1) & 3)]
        return u8[1118 + d + (u & 1)]

    def value(u):
        cat, pos = values[index(u)]
        if cat not in CATEGORY:  # Khmer's and Myanmar's own categories: not this shaper's
            return 0 | (14 << 8)
        return CATEGORY[cat] | (POSITION[pos] << 8)

    ranges = []
    previous = None
    for u in range(0x110000):
        v = value(u)
        if v != previous:
            ranges.append((u, v))
            previous = v

    ucd = sys.argv[2]
    excluded = set()
    for line in open(os.path.join(ucd, "CompositionExclusions.txt"), encoding="utf-8"):
        line = line.split("#")[0].strip()
        if line:
            excluded.add(int(line.split("..")[0], 16))
    marks = set()
    decomposition = {}
    for line in open(os.path.join(ucd, "UnicodeData.txt"), encoding="utf-8"):
        f = line.split(";")
        cp = int(f[0], 16)
        if f[2] in ("Mn", "Mc", "Me"):
            marks.add(cp)
        if f[5] and not f[5].startswith("<"):
            parts = [int(x, 16) for x in f[5].split()]
            if len(parts) == 2:
                decomposition[cp] = parts
    def full(cp):
        # The full canonical decomposition, as HarfBuzz's recursive decompose gives it (its exceptions kept whole).
        if cp in (0x0931, 0x09DC, 0x09DD, 0x0B94) or cp not in decomposition:
            return [cp]
        a, b = decomposition[cp]
        if not (a in marks or cp in excluded):
            return [cp]  # composed again: it stays as it is
        return full(a) + full(b)

    decompositions = []
    for cp in sorted(decomposition):
        if 0x0900 <= cp <= 0x0DFF:
            parts = full(cp)
            if len(parts) > 1:
                decompositions.append((cp, parts[0], parts[1], parts[2] if len(parts) > 2 else 0))

    # Pairs HarfBuzz composes again after decomposing: a base and the mark after it, into a character that is not
    # a composition exclusion; and HarfBuzz's own Bengali YA + NUKTA.
    compositions = []
    for cp in sorted(decomposition):
        a, b = decomposition[cp]
        if 0x0900 <= cp <= 0x0DFF and a not in marks and cp not in excluded:
            compositions.append((a, b, cp))
    compositions.append((0x09AF, 0x09BC, 0x09DF))
    compositions.sort()

    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(here, "..", "..", "ceeui", "src", "indic_data.cee")
    lines = [
        "// SPDX-License-Identifier: MIT",
        "// Generated by tools/unicode/build_indic.py from HarfBuzz's Indic table (MIT) and the Unicode character",
        "// database: do not edit.",
        "",
        f"/// How many ranges INDIC_RANGES holds.",
        f"const INDIC_RANGE_COUNT: usize = {len(ranges)};",
        "",
        "/// Every code point's Indic category (bits 0-7) and position (bits 8-15) as (first code point, value) pairs,",
        "/// sorted; a range runs to the next pair's first code point.",
        f"const INDIC_RANGES: [u32; {len(ranges) * 2}] = [",
    ]
    for k in range(0, len(ranges), 6):
        lines.append("    " + ", ".join(f"0x{a:X}, 0x{b:X}" for a, b in ranges[k:k + 6]) + ",")
    lines += [
        "];",
        "",
        f"/// How many decompositions INDIC_DECOMPOSITIONS holds.",
        f"const INDIC_DECOMPOSITION_COUNT: usize = {len(decompositions)};",
        "",
        "/// The Indic characters the shaper decomposes, as (character, its parts: two or three, 0 for none), sorted.",
        f"const INDIC_DECOMPOSITIONS: [u32; {len(decompositions) * 4}] = [",
    ]
    for k in range(0, len(decompositions), 4):
        lines.append("    " + ", ".join(f"0x{a:X}, 0x{b:X}, 0x{c:X}, 0x{e:X}" for a, b, c, e in decompositions[k:k + 4]) + ",")
    lines += [
        "];",
        "",
        f"/// How many compositions INDIC_COMPOSITIONS holds.",
        f"const INDIC_COMPOSITION_COUNT: usize = {len(compositions)};",
        "",
        "/// The pairs the shaper composes (when the font has the result), as (base, mark, composed), sorted.",
        f"const INDIC_COMPOSITIONS: [u32; {len(compositions) * 3}] = [",
    ]
    for k in range(0, len(compositions), 5):
        lines.append("    " + ", ".join(f"0x{a:X}, 0x{b:X}, 0x{c:X}" for a, b, c in compositions[k:k + 5]) + ",")
    lines += ["];", ""]
    open(out, "w", encoding="utf-8").write("\n".join(lines))
    print(f"build_indic.py: {len(ranges)} ranges, {len(decompositions)} decompositions -> {os.path.relpath(out)}")


if __name__ == "__main__":
    main()
