"""Builds ceeui/src/indic_machine_data.cee: the state tables of HarfBuzz's Indic syllable machine (Ragel output,
src/hb-ot-shaper-indic-machine.hh, MIT licence; see THIRD_PARTY_NOTICES), which ceeui/src/indic.cee runs.

    python3 tools/unicode/build_indic_machine.py HARFBUZZ_SRC
"""

import os
import re
import sys

ARRAYS = [
    ("trans_keys", "INDIC_TRANS_KEYS", "u8"),
    ("key_spans", "INDIC_KEY_SPANS", "u8"),
    ("index_offsets", "INDIC_INDEX_OFFSETS", "u16"),
    ("indicies", "INDIC_INDICIES", "u8"),
    ("trans_targs", "INDIC_TRANS_TARGS", "u8"),
    ("trans_actions", "INDIC_TRANS_ACTIONS", "u8"),
    ("to_state_actions", "INDIC_TO_STATE_ACTIONS", "u8"),
    ("from_state_actions", "INDIC_FROM_STATE_ACTIONS", "u8"),
    ("eof_trans", "INDIC_EOF_TRANS", "u16"),
]


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    src = open(os.path.join(sys.argv[1], "hb-ot-shaper-indic-machine.hh"), encoding="utf-8").read()
    lines = [
        "// SPDX-License-Identifier: MIT",
        "// Generated by tools/unicode/build_indic_machine.py from HarfBuzz's Indic syllable machine (MIT): do not",
        "// edit.",
        "",
        "const INDIC_START: u32 = %s;" % re.search(r"indic_syllable_machine_start = (\d+);", src).group(1),
        "",
    ]
    for name, const, kind in ARRAYS:
        body = re.search(r"_indic_syllable_machine_%s\[\] = \{(.*?)\};" % name, src, re.S).group(1)
        values = [int(x) for x in re.findall(r"-?\d+", body)]
        lines.append(f"const {const}: [{kind}; {len(values)}] = [")
        for k in range(0, len(values), 16):
            lines.append("    " + ", ".join(str(v) for v in values[k:k + 16]) + ",")
        lines += ["];", ""]
    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(here, "..", "..", "ceeui", "src", "indic_machine_data.cee")
    open(out, "w", encoding="utf-8").write("\n".join(lines))
    print(f"build_indic_machine.py -> {os.path.relpath(out)}")


if __name__ == "__main__":
    main()
