"""Writes ../src/templates.cee from the files beside this script: the app `claywind-pack new` makes. Run it after
changing them:

    python3 template/make_templates.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
# The files of a new app, as they are named in it (gitignore becomes .gitignore).
FILES = [("ceesafe.toml", "ceesafe.toml"), ("README.md", "README.md"), ("gitignore", ".gitignore"),
         ("src/main.cee", "src/main.cee"), ("src/app.cee", "src/app.cee")]


def literal(text):
    out = []
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ord(ch) < 32 or ord(ch) > 126:
            out.append("\\u{%X}" % ord(ch))
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def main():
    lines = ["// SPDX-License-Identifier: MIT",
             "// Generated by template/make_templates.py from the files in template/: the app `claywind-pack new`",
             "// makes. __NAME__ is the app's name; __DEPS__ its dependencies on ClayWind's packages.", "",
             "/// How many files a new app has.", "const TEMPLATE_COUNT: usize = %d;" % len(FILES), "",
             "/// Each file's path in the new app.",
             "static TEMPLATE_PATHS: [StringView; %d] = [" % len(FILES)]
    lines += ["    %s," % literal(path) for _, path in FILES]
    lines += ["];", "", "/// Each file's text.", "static TEMPLATE_TEXTS: [StringView; %d] = [" % len(FILES)]
    for name, _ in FILES:
        with open(os.path.join(HERE, name), encoding="utf-8") as f:
            lines.append("    %s," % literal(f.read()))
    lines += ["];", ""]
    with open(os.path.join(HERE, "..", "src", "templates.cee"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
